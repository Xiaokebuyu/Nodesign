import { t } from '../lib/i18n.js';

/**
 * 「回头提炼」那条路发出去的第一句话（2026-08-29）
 *
 * 橱窗一直是空的，不是因为 crystallize_skill 坏了 —— 它好好的，是那个环闭不上：
 * 产生一条橱窗数据要用户在**会话里**说「把这套风格留下来」，而这句提示写在
 * **橱窗页**的空状态里，只有已经点进橱窗的人才看得到，看到的时候人不在会话里。
 * 这条路把动作挪到看得见提示的地方：在橱窗上点一个做过的项目，直接在那个项目里
 * 起一个新会话，第一句话就是这段。
 *
 * 为什么是「新会话」而不是后台无头跑一遍：跑的过程用户看得见、能中途改口，
 * 出岔子也在他眼前。而且 crystallize_skill 写进去的 skill 本来就只在**新会话**
 * 里生效，这条路顺带把那件事也办了。
 *
 * ⚠️ 这段是**用户消息**，会以气泡的形式出现在会话里，所以跟着界面语言走。
 * 拆成整句进词表而不是整段包一个 key：四个要点各自是完整的一句话，翻译的时候
 * 不用在一个巨型字符串里数换行。组装在这里做，词表只管句子。
 */

/** 设计项目：收的是排版和取色背后的判断 */
const DESIGN = () => ({
  lead: t('把这个项目回头看一遍，帮我把这套做法固化成一个我自己的 skill。'),
  read: t('先读项目里已经留下的东西：产物文件、板书、记忆。然后整理这几样：'),
  points: [
    t('具体取值：字号阶梯、配色、间距节奏、圆角和描边怎么用的，以及为什么是这些数'),
    t('判断依据：这个气质为什么合这个场合，哪里是刻意压住的'),
    t('走过的弯路：哪些做法被换掉了，为什么'),
    t('边界：这套东西放到什么场合会失效'),
  ],
});

/** 演出项目：同一个问法换一套内容轴，问设计 token 在这挡里全是错的方向 */
const RP = () => ({
  lead: t('把这个项目回头看一遍，帮我把这套演法固化成一个我自己的 skill。'),
  read: t('先读项目里已经留下的东西：板书、角色卡、记忆。然后整理这几样：'),
  points: [
    t('调子怎么定的：节奏、视角、留白的分寸'),
    t('角色怎么立起来的，哪些设定是关键的'),
    t('走过的弯路：哪些写法被换掉了，为什么'),
    t('边界：这套演法放到什么故事上会失效'),
  ],
});

/**
 * 组装第一句话。
 *
 * 结尾那句「存完说清楚你写了什么边界」不是客套：crystallize_skill 的
 * frontmatter description 是将来路由到这个 skill 的唯一信号，边界写歪了要等到
 * 半年后某次它在错的场合被选中才发作。趁用户还在场当面对一次最便宜。
 *
 * @param {'design'|'rp'} [mode]
 * @returns {string}
 */
export function distillPrompt(mode) {
  const { lead, read, points } = mode === 'rp' ? RP() : DESIGN();
  return [
    lead,
    '',
    read,
    ...points.map((p) => `- ${p}`),
    '',
    t('整理完先讲要点给我听，然后用 crystallize_skill 存下来。存完说清楚你写了什么边界，写歪了我当场改。'),
  ].join('\n');
}
