/**
 * 树影与灯的着色器（2026-09-02 从 home-canopy.js 拆出来）。
 *
 * 拆的理由只有一条：那个文件胖过 600 行的棘轮了，而这里是**另一种语言**——
 * 一边是 GLSL 的每像素运算，一边是 JS 的挂载、风、帧率、纹理上传。
 * 两边的接口就是下面那张 uniform 表，改一个名字要动两处，别的耦合没有。
 *
 * 想知道整层是怎么回事、为什么分两块画布、为什么夜是"把光收走"，
 * 看 home-canopy.js 的文件头；那儿是这一层的说明书。
 */

export const VERT = `
attribute vec2 aPos;
varying vec2 vUv;
void main() {
  // y 翻过来：着色器里 vUv.y = 0 就是屏幕顶上，跟"光从右上来"这句话对得上
  vUv = vec2(aPos.x * 0.5 + 0.5, 0.5 - aPos.y * 0.5);
  gl_Position = vec4(aPos, 0.0, 1.0);
}`;

export const FRAG = `
#ifdef GL_FRAGMENT_PRECISION_HIGH
precision highp float;
#else
precision mediump float;
#endif
varying vec2 vUv;

uniform vec2  uRes;      // 画布像素，只用来取长宽比
uniform float uFlow;     // 风走过的路。⚠️ 不是时间：阵风的时候它走得快
uniform float uT;        // 真的时间（秒），只给摆动用
uniform float uElev;     // 太阳有多高 0…1。⛔ 不是 alt：这个折算过季节（见 daylight.js）
uniform vec2  uCast;     // 影子的去向（单位向量）。纸的影子读的是同一个数
uniform float uLen;      // 影子有多长（倍数）
uniform float uGain;     // 光有多强，秋天正午 = 1
uniform float uWarm;     // 光的暖度 0…1
uniform float uNight;    // 夜的程度 0…1
uniform float uGust;     // 这一阵风的强度 0…1
uniform float uOver;     // 0 = 底层，1 = 压在内容上那层
uniform vec3  uLit;      // 当季的光（season.js）
uniform vec3  uGold;     // 当季的斜阳
uniform vec3  uDusk;     // 当季的暗斑
uniform vec3  uNightC;   // 夜色
uniform vec3  uLampC;    // 台灯
uniform vec2  uFrom;     // 光从哪儿来（uv，y 向下）
uniform vec3  uTint;     // 时段的整片色偏
uniform float uTintA;
uniform sampler2D uOccl; // 遮挡图：红=纸有多高，alpha=这儿是不是纸
uniform float uHasOccl;  // 这一帧有没有纸（一张都没有就整段跳过）
uniform float uThrow;    // 影子投多远（uv 单位）
uniform float uSoft;     // 半影多宽
uniform float uPoint;    // 0=平行光（太阳），1=近处的点光源（台灯）
uniform sampler2D uCanopy; // 树冠：R/G/B 三层叶子，从上到下（home-canopy-texture.js）
uniform float uCanScale; // 树冠图在一屏里铺几遍
uniform float uLeafA;    // 叶影压多重
uniform float uBias;     // mip 偏置 = 太阳低的时候整片影子软下来
uniform vec2  uWinC;     // 窗光落在桌上那块亮区的中心（uv）
uniform vec2  uWinR;     // 它的半宽 / 半长（x 垂直于光，y 顺着光）
uniform float uWinSoft;  // 边有多软（相对半径的比例）
uniform float uLeaves;   // 树冠开关：1 = 有叶影，0 = 只剩一片素净的光

float hash(vec2 p) {
  p = fract(p * vec2(123.34, 345.45));
  p += dot(p, p + 34.345);
  return fract(p.x * p.y);
}

float vnoise(vec2 p) {
  vec2 i = floor(p), f = fract(p);
  // smootherstep 不是 smoothstep：叶隙的边要是有折线，一放大就露馅
  vec2 u = f * f * f * (f * (f * 6.0 - 15.0) + 10.0);
  return mix(mix(hash(i),                hash(i + vec2(1.0, 0.0)), u.x),
             mix(hash(i + vec2(0.0,1.0)), hash(i + vec2(1.0, 1.0)), u.x), u.y);
}

/**
 * ⭐⭐⭐ 风场：这一刻，这一点头顶上的那片树冠被吹到哪儿去了（纹理坐标的位移）。
 *
 * 09-02 站主第四次判词：**「所有叶片影子带上枝丫作为一个整体做无规律晃动…
 * 现在看起来就像是一堆独立的叶片」**。量下来他说的是真的：相邻两格的位移方向
 * 余弦只有 0.58（1 = 一起走，0 = 各走各的），共同位移只占 69%。
 *
 * 病根在**从前根本没有"场"**，只有三个各自为政的常数偏移：三层分别乘
 * 「+w ／ -0.68w ／ +0.31w」 —— 也就是说三层叶子在**朝相反方向**切过彼此。
 * 三片叶子从你眼前朝三个方向走过去，眼睛没法把它们归成一棵树。
 *
 * ## ⭐⭐ 为什么答案不是"那就让整片一起动"
 *
 * 整片一起动就是 08-30 被同一个人否掉的那张**滑动的贴图**（对照组量出来
 * cos 0.97 / 共同位移 99% / 变形 2px，一眼就是在滑）。这两条判词看着矛盾，
 * 其实是同一根轴的两头，而正确答案不在中间某个配比上 —— 在**换一种运动**：
 *
 *   平移        处处同一个位移      → 贴图
 *   各自为政    处处无关的位移      → 散沙
 *   **形变**    位移随位置**平滑**变化 → 树
 *
 * 一簇叶子（约 0.05 个屏宽）内部几乎同相，所以叶子带着枝丫一起走（整体）；
 * 而整屏跨了大半个波长，所以左半边和右半边不同相 —— 任何一帧都不是另一帧的
 * 平移（无规律）。**两条判词一起满足，而且这正是一棵树真实的动法**：
 * 树冠是一个在形变的东西，不是一块在平移的板子。
 */
vec2 windField(vec2 p) {
  // 风向自己在游移。⭐ 定死一个方向的话，摆动会摆出节拍感 —— 真风不会这样。
  float turn = sin(uT * 0.137) * 0.34 + sin(uT * 0.061 + 1.7) * 0.26;
  vec2 dir = vec2(cos(0.42 + turn), sin(0.42 + turn));
  vec2 nrm = vec2(-dir.y, dir.x);
  // ⭐⭐ 一阵风是**一道横过树冠的波**，不是整片同时动：相位里带着"沿风向走了多远"。
  // ⚠️ 这个系数是波长的倒数，是这整件事最要紧的一个数：
  //      调大 → 波长短 → 一簇叶子内部就被拧开了，退回"一堆独立的叶片"
  //      调小 → 波长长 → 整屏同相，退回"一张滑动的贴图"
  //    3.0 是约 0.75 个波长铺满一屏：一簇叶子里相位差 0.17 弧度（几乎同相），
  //    而左右两头差着大半个波长。
  float ph = dot(p, dir) * 3.0;
  // 三个不通约的频率叠起来：永不重复，听不出节拍 —— "无规律"是这么来的
  float sw = sin(ph - uT * 1.02)
           + 0.58 * sin(ph * 1.73 - uT * 1.61 + 1.3)
           + 0.34 * sin(ph * 0.47 - uT * 0.58 + 4.1);
  // 侧向那一点：枝条不只是前后摆，它在划弧
  float cr = 0.52 * cos(ph * 0.81 - uT * 0.74 + 2.4)
           + 0.30 * sin(ph * 1.29 - uT * 1.27 + 0.6);
  // ⭐ 这一带的枝吃不吃得住风：有的整簇甩得凶，有的几乎不动。
  //   噪声的格子约 0.6 个屏宽，比一簇叶子大得多 —— 它分的是"哪几根枝"，不是"哪几片叶"。
  float grip = 0.38 + 1.05 * vnoise(p * 1.60 + vec2(11.3, 5.7));
  // ⚠️ 前一项是**没风的时候**的底。收得太狠（0.0026）整片树影就冻住了 ——
  //    阵风六到二十二秒才来一趟，其余时间屏幕上什么都不动，读起来像坏了。
  //    真实的树在微风里也一直在轻轻晃，只是幅度小一个量级。
  return (dir * sw + nrm * cr) * ((0.0105 + uGust * 0.0620) * grip);
}

/**
 * ⭐⭐⭐ 窗光：这一点在不在那块光里（0 = 完全在光外，1 = 光心）。
 *
 * 09-02 收到的判词是「这种拟物化的语言不是当前主流」。拆下来最要害的一条是：
 * **叶影铺满整个视口，没有边界。没有边界的影子是纹理，有边界的影子才是物体。**
 * 满屏半透明叶影正是 2019 到 2022 年素材站上最泛滥的那张模板贴图，而观众看不见
 * 我们的着色器，只看得见画面 —— 「机制上是真的」在这里救不了它。
 *
 * 真实的树影一定有边：窗框的边，或者树冠的边，边外是均匀的光。所以这里给光
 * 一个形状：光源在哪儿（sunFrom）决定这块亮区甩到哪儿，太阳多低（cast.len）
 * 决定它多长、多软。它一天里会自己从这头走到那头，而这比整页染色强得多。
 *
 * ⭐ 用超椭圆不用圆也不用矩形：圆读作聚光灯，矩形读作一个 div，
 *   四次方的超椭圆是一块有角但角是圆的光斑，最接近窗子投在桌上的样子。
 * ⭐ 边上加一层低频噪声：直边读作几何图形，碎边才读作树冠的边缘。
 */
float windowLight(vec2 p, vec2 c, vec2 n, float ar) {
  vec2 d = (p - uWinC) * vec2(ar, 1.0);
  vec2 q = vec2(dot(d, n), dot(d, c)) / uWinR;
  float t = pow(pow(abs(q.x), 4.0) + pow(abs(q.y), 4.0), 0.25);
  t += (vnoise(p * 3.4 + vec2(uFlow * 0.06, 0.0)) - 0.5) * 0.24;
  return 1.0 - smoothstep(1.0 - uWinSoft, 1.0 + uWinSoft, t);
}

/**
 * ⭐⭐ 这一点头顶上被几层叶子挡着。返回 0（缝，全亮）到 1（三层都挡着，深荫）。
 *
 * 三层叶子塞在同一张图的 R / G / B 里（见 home-canopy-texture.js）。这儿做三件事：
 *
 *   **视差**   上面那层离桌面远，投得远、走得快；底下那层近，跟着地面走。
 *              三层的采样坐标于是各不相同 —— 这是"树冠有厚度"的全部来源。
 *   **相乘**   透光率是乘起来的，不是加起来的：光要穿过三层叶子才落到桌上。
 *              ⭐ 相加只会得到一片灰；相乘才会有「三层的缝正好对齐」那种全亮的
 *              日斑，和「三层都挡着」那种很深的暗。
 *   **半影**   mip 偏置。太阳低的时候影子软，uBias 一大，采到的就是糊过的那一级。
 *              ⭐ 上层比下层多糊一点：它离桌面远，半影本来就张得开。
 *
 * ⛔ 别把三层合成一张图预乘好。合好了就只剩一张图在平移 —— 那正是 08-30 被
 *   站主判成「只是一个贴图」的那条老路。**婆娑是层与层之间的相对错动**：
 *   缝会张开、合上、并到一起、灭掉，变的是图案本身不是图案的位置。
 */
float leafShade(vec2 p, vec2 wind, vec2 windLow) {
  // 慢慢流过去的那一点：空气在流，整片树冠**同向**慢慢挪。
  // ⚠️ 系数从 0.42 收到 0.10：阵风让树冠**摆**，不该让它**跑** —— 从前一阵风
  //    里这一项能把上层推出去六十多个像素，把摆动整个盖住了。
  vec2 w = vec2(uFlow * 0.065, uFlow * 0.036);
  float k = uCanScale;
  // ⭐⭐⭐ 三层**同向**，只有深浅之别（越高的层离桌面越远，影子的位移放得越大）。
  // ⛔ 从前是 「+w ／ -0.68w ／ +0.31w」 —— 三层朝**相反**方向切过彼此，那正是
  //    「看起来像一堆独立的叶片」的病根。
  // ⭐ 同向不等于同步：三层的 k 不一样（1 / 1.13 / 1.31），同一个 wind 换算到
  //    屏幕上是 1.00 / 0.77 / 0.57 —— 上下两层仍差着 1.75 倍，缝照样张开合上，
  //    婆娑一点没丢。丢掉的只是"朝反方向"这一件事。
  // ⭐⭐ 层与层之间**同向但快慢差得多**（屏幕上 1.00 / 0.69 / 0.43），而且下面
  // 两层吃的是**错开一点的那阵风**（windLow）—— 风先摇到树顶，隔一会儿才摇到
  // 下层，所以三层永远差着一点相位。缝就是这么张开、合上、并到一起、灭掉的。
  // ⚠️ 这一项是"婆娑"的全部来源，也是唯一让它不塌成一张平移贴图的东西：
  //    把三层的系数调成一样，它立刻变成一张滑动的贴纸（扫出来残差只剩一成多）。
  vec3 t;
  t.r = texture2D(uCanopy, p * k        + w        + wind,        uBias + 0.30).r;
  t.g = texture2D(uCanopy, p * k * 1.13 + w * 0.93 + mix(wind, windLow, 0.5) * 0.78
                  + vec2(0.37, 0.19),                             uBias + 0.12).g;
  t.b = texture2D(uCanopy, p * k * 1.31 + w * 0.86 + windLow * 0.56
                  + vec2(0.71, 0.63),                             uBias).b;
  return 1.0 - (1.0 - t.r) * (1.0 - t.g) * (1.0 - t.b);
}

/**
 * ⭐⭐ 这一点上方有没有纸挡着光。
 *
 * 沿着光射来的方向往回走几步，看路上有没有纸。走的方向分两种：
 *
 *   平行光（太阳）  处处同一个方向。远处的光源，影子全都平行
 *   点光源（台灯）  方向是**从灯指向这一点**，所以影子从灯那儿放射开来 ——
 *                   左边的卡朝左下、右边的卡朝右下。这正是从前那套
 *                   「全屏一个方向」最假的地方
 *
 * 两种用 uPoint 揉在一起（白天 0、夜里 1），中间每一帧都是成立的画面。
 *
 * ⛔ 从 t=0.18 起步不从 0 起步：0 那一步采到的是这张纸**自己**，
 *   一张纸不会把自己盖在自己的影子里。
 */
float castShadow(vec2 p, float ar, float selfH) {
  if (uHasOccl < 0.5) return 0.0;
  vec2 par = uCast;                                   // 平行光的方向
  vec2 rad = normalize((p - uFrom) * vec2(ar, 1.0) + vec2(0.0, 1e-4));
  vec2 dir = normalize(mix(par, rad, uPoint));
  // 近处的灯：离得越远影子越长
  float far = mix(1.0, 0.55 + length((p - uFrom) * vec2(ar, 1.0)) * 1.6, uPoint);
  // ⭐⭐⭐ 给投射距离封顶。
  // 站主 09-02：「晚上切换到台灯，阴影没处理好」。算下来夜里的最大投射距离是
  // uThrow × far × 2.25 = 0.104 × 2.15 × 2.25 ≈ **0.50 uv，452 个像素**，
  // 而白天只有 89。一张 40 像素厚的纸投出半屏长的影子本身就不对，更要命的是
  // 十二个采样点铺不满这么长的距离 —— 影子会**断成一条条硬边的条带**，
  // 输入纸那张更是拉成一个带折角的巨大楔形。
  // ⚠️ 封在着色器里而不是改 LAMP_CAST.len：那个常量同时喂着纸上的 CSS 接触影，
  //    动它会把另一处一起改了。
  float thr = min(uThrow * far, 0.075);
  vec2 nrm = vec2(-dir.y, dir.x);
  float acc = 0.0;
  // ⭐⭐⭐ 每个像素把行进的起点**错开一点点**（0 到 1 步之间的随机相位）。
  //
  // ⛔ 09-02 把输入纸那两片签加进遮挡表之后，它们的影子是一段一段的**阶梯**，
  //   步长约 15 像素。第一反应是遮挡图太糙（半分辨率 ≈ 4.8 像素一格），升到
  //   全分辨率之后阶梯**原样还在** —— 病根不在图，在行进本身：12 个采样点铺在
  //   112 像素上，每 9 像素落下一个矩形副本，边缘就叠出台阶。大张的纸看不出来，
  //   小而边缘清楚的东西一进表就露馅。
  // ⭐ 加采样点是线性变贵；错开相位不花钱，把条带换成极细的噪点，
  //   而噪点在一片软影子上眼睛读作平滑。
  float jit = hash(gl_FragCoord.xy * 0.7);
  // ⚠️ 采样点从 8 个加到 12 个。步长 = 总长 / 点数，点数不够的话长影子必然断成条带。
  for (int i = 0; i < 12; i++) {
    // d = 沿光线往回走了多远（uv）。走满 2.4 个「一张卡的高度」，
    // 因为最高的那摞纸就是 2.2，揭起来的那张最多抬到 2.5（见 home-occluders.js 的 OCCLUDERS）
    float d = thr * (0.12 + (float(i) + jit) * 0.195);
    // ⭐ 半影随距离张开：八个采样点排成一个**锥形**，近的挤在中轴上、远的甩开，
    //   这正是半影的形状。⚠️ 第一版这个系数小了两个数量级（横向只挪 0.5 像素），
    //   于是影子是刀切的矩形 —— 调出来夸张档才看见，看着像贴了张纸不像影子。
    // ⭐⭐⭐ **往回走，朝着光走**，不是顺着影子的去向走。
    // dir 是「影子落向哪儿」（跟 paper.js 那条 box-shadow 的 offset 同一个量）。
    // 一点要在影子里，挡光的那张纸必须在它**朝光**的一侧，也就是 p - dir*d。
    // ⛔ 从前写的是 +dir*d，等于顺着下游找遮挡物 —— 于是影子落在每张卡**朝光
    //    的那一面**：夜里灯在右上，影子就出现在右上。站主一眼看出来「不符合常理」。
    //    这个符号从 09-01 起就是反的，只是当初影子只有 8-10 个灰阶没人看得出来；
    //    这一轮把它抬到 19 个灰阶，就藏不住了。
    // ⚠️ 纸上那条 CSS 接触影一直是对的（paper.js 直接用 cast 当 offset），
    //    所以同一张卡上两条影子分别在两边 —— 滚动时那种"抖"有一半是这么来的。
    vec2 off = -dir * d + nrm * (d * uSoft * (float(i) - 5.5) * 0.115);
    vec4 o = texture2D(uOccl, p + off / vec2(ar, 1.0));
    // 一块高 h 的纸，影子只能投出 h 那么远。o.r 存的是 h/4
    // ⭐ o.g = 这是一张**松动的纸**（正被揭掉的复制品，见 home-occluders.js 的 LOOSE）：
    //   它投到别的纸上的影子只按**抬起的那一截**算 —— 飞过输入纸时离纸面只有零点几
    //   张纸高，影子该是贴着边缘的一道细线，按整个高度算是一整块黑板压在纸上。
    //   ⛔ 桌上钉着的纸（o.g = 0）照旧按整个高度：邻居之间那点错高投出来的长影子
    //   是有意的，深度全靠它，别顺手"修正"成物理量。
    //   max(…, 1e-4)：reach 归零时 smoothstep 两个边相等是未定义行为。
    float reach = max((o.r - selfH * o.g) * 4.0 * thr, 1e-4);
    // 尖端软收，别在 reach 那儿一刀切。⚠️ 收得比原来更长（1.15→0.30 而不是
    //   1.02→0.45）：影子一长，硬收尾就成了画面上一条笔直的边，很显眼。
    acc += o.a * smoothstep(reach * 1.15, reach * 0.30, d) * step(selfH + 0.03, o.r);
  }
  // 12 个点比 8 个点多攒了一半，除数跟着走，浓淡不变
  return clamp(acc / 4.8, 0.0, 1.0);
}

/** src 盖在 dst 上（直通 alpha，不是预乘） */
vec4 lay(vec4 dst, vec3 c, float a) {
  float na = a + dst.a * (1.0 - a);
  return vec4((c * a + dst.rgb * dst.a * (1.0 - a)) / max(na, 1e-5), na);
}

void main() {
  float ar   = uRes.x / max(uRes.y, 1.0);
  float day  = 1.0 - uNight;
  float alt  = clamp(uElev, 0.0, 1.0);

  // ⭐⭐ 光的坐标架：c 是影子的去向，n 是它的法线。
  // **c 就是纸上那些 box-shadow 用的同一个向量**（两边都来自 daylight.js 的
  // castAt）。太阳转到哪边，树影和纸影一起转 —— 一个光源，两个后果。
  vec2 c = normalize(uCast + vec2(0.0, 1e-4));
  vec2 n = vec2(-c.y, c.x);

  vec2 p = vec2(vUv.x * ar, vUv.y);

  // ⭐ 树冠投在桌上的这一片，是顺着光的去向**平移**过来的。太阳从东走到西，
  // 斑驳跟着从这头挪到那头 —— 光斑不是原地闪烁，它整天都在走。
  p += c * (0.34 * uLen);

  // ⭐ 太阳低的时候光是掠射的，叶隙的像被拉长 —— 而且是**沿着影子的方向**拉长，
  // 不是永远沿着屏幕的横轴（从前那版写的是 p.x *= …，等于假设光永远在正右上）。
  // 转进光的坐标架里压一压，再转回来。
  vec2 q = vec2(dot(p, n), dot(p, c));
  q.y *= mix(0.42, 1.0, alt);
  p = n * q.x + c * q.y;

  // ⭐⭐ 风。位移**随位置平滑变化** —— 一簇叶子内部几乎同相（所以叶子带着枝丫
  // 一起走），整屏跨大半个波长（所以图案在形变不在平移）。细节见 windField。
  vec2 wind = windField(p);
  // 下面两层吃的那阵风：在场里错开一点取样 = 差着一点相位（风摇到下层要晚一步）
  vec2 windLow = windField(p + vec2(0.23, -0.17));

  // ⭐⭐ 三层真叶子的遮蔽。0 = 缝（全亮），1 = 三层都挡着（深荫）。
  // ⭐⭐⭐ uLeaves = 0 的时候整个树冠不参与，桌上只剩一片素净的光。
  // 站主 09-02 的判词：「就那一小块树影斑驳，还不如素色」「对于我们这种强调
  // 沉浸专注和具有文学气质的应用，加入这么个看起来非常吵闹的样式会不会很差劲」。
  // 他是对的：真正需要实时算的是纸对纸的投影（8-10 灰阶），而纯装饰的叶影是 23，
  // 最值钱的一层被最像贴图的一层盖着。
  float shade = uLeaves > 0.0 ? leafShade(p, wind, windLow) * uLeaves : 0.0;

  // ⭐⭐⭐ 这块光有多大、在哪儿。光区外没有直射光，也就没有叶影 ——
  // 那儿是均匀的环境光，桌面安静。
  // ⭐⭐ 没有叶子的时候不要这块遮罩。它当初的全部作用是给斑驳划一条边；
  //   斑驳没了，一块有边的亮区就只是一片贴上去的浅色，读作聚光灯不读作日光。
  //   素色版里白天只剩一层很宽很淡的方向性明暗，光的方向交给纸的投影去说。
  float win = uLeaves > 0.0 ? windowLight(vUv, c, n, ar) : 1.0;
  float leaf = shade * win;

  // 树冠不是一整片一样厚 —— 很低频的一层噪声让这半边密那半边疏，
  // 免得整屏的叶子平均得像壁纸。
  //
  // ⭐⭐⭐ 这一层**必须跟着树冠一起动**。它从前挂在 uFlow 上匀速平移，而它是
  // 整个画面里尺度最大、对比最强的一层 —— 于是屏幕上真正在动的那个东西是
  // 一张匀速滑过去的大噪声，一帧走 19 个像素，比叶子本身还快。分块匹配一量
  // 就锁在它身上（共同位移占比 98%），眼睛读到的也是它：**一整片在滑**。
  // ⚠️ 系数 0.657 = 1.15 / uCanScale：它的坐标尺度跟叶子那层不一样，
  //    换算过才是"同样的屏幕位移"，直接加 wind 会让它比叶子快 1.5 倍。
  float dens = 0.72 + 0.52 * vnoise(p * 1.15 + (vec2(uFlow * 0.10, uFlow * 0.055) + wind) * 0.657);
  leaf = clamp(leaf * dens, 0.0, 1.0);

  // 靠光源那一侧亮，远处淡下去
  vec2 d = (vUv - uFrom) * vec2(ar, 1.0);
  // ⚠️ 素色版里衰减要陡得多。0.55 那档整屏的 near 只在 0.58 到 1.0 之间，
  //    桌面几乎是均匀的 —— 实测三个白天时刻并排看**一模一样**，光什么都没说。
  //    陡一点，桌面才有"这边亮那边暗"，而这边是哪边一天里会变。
  float near = exp(-dot(d, d) * (uLeaves > 0.0 ? 0.55 : 1.45));

  // 缝里漏下来的那点太阳。**只在窗内**：光区外本来就没有直射光可漏。
  // ⚠️ 这里用 shade 不用 leaf。leaf 已经乘过 win 了，再拿 (1 - leaf) 去算亮度，
  //    光区外会得到 (1 - 0) = 1，也就是**全亮**，正好反了。⛔ **只画在底层**：底层压在台面上（台面是暗的，提亮
  // 有地方去），顶层压在纸上 —— 而纸的亮度已经 250 了，往白纸上加光等于什么都没做。
  // 这一条是「光源看起来不明显」的一半病根。
  // ⚠️ 素色版的量要小得多：没有叶隙把它切碎，同样的量会读成"整片桌子变亮了"。
  float light = (1.0 - shade) * win * mix(uLeaves > 0.0 ? 0.52 : 0.10, 1.0, near);

  vec3 sunC = mix(uLit, uGold, uWarm * 0.75);

  vec4 acc = vec4(0.0);
  // 台面上的暖光，只在底层
  // ⚠️ 0.30 → 0.44：光收成一块之后面积小了，得更亮才看得出这是**一束光**
  //    而不是一片浅色。亮区更小更亮，是它跟"一层滤镜"的分界。
  acc = lay(acc, sunC, light * day * (1.0 - uOver) * (uLeaves > 0.0 ? 0.44 : 0.42) * uGain);
  // ⭐ 背光那半边也要暗下去。只加亮不压暗，梯度只有一半，而且整片桌子会越来越白。
  //   ⛔ 只画在底层：压暗内容会吃对比度，而这一笔纯粹是桌面的事。
  if (uLeaves <= 0.0) {
    acc = lay(acc, mix(uDusk, uNightC, 0.35), (1.0 - near) * day * (1.0 - uOver) * 0.16);
  }
  // ⭐⭐⭐ **叶影画在顶层。** 从前它带着 (1.0 - uOver)，只画在底层 —— 而底层在
  // 所有卡片**底下**，于是「树叶的影子打在纸上」这件事一笔都没发生过，站主说
  // 「没有我想要的那种真实的树影婆娑」就是它。树在所有东西的上头，它的影子
  // 该落在台面上，也该落在纸上、字上。
  //
  // ⭐ 影子的颜色不是黑，是**天光**：叶子挡掉的只是直射的太阳，剩下来的是天上
  // 那一片蓝。所以往冷里偏 —— 涂一层褐的才是把纸弄脏。
  // ⚠️ 顶层压的是内容，纸暗一分字也暗一分，对比度是要还的。uLeafA 的上限是
  //    量出来的，判据是 lens.mjs contrast 跟改动前并排，别凭观感往上加。
  // ⭐ 0.62 偏得比看上去该有的多。暗斑色 uDusk 是暖褐的（它本来是画在台面上的），
  //   拿它直接当叶影，白纸上会读成一块**污渍**而不是影子 —— 影子偏冷才对。
  acc = lay(acc, mix(uDusk, uNightC, 0.62), leaf * day * uOver * uLeafA);
  // ⭐⭐ 真正投出来的影子。**只画在顶层**：它得能落在桌面上，也得能落在别的纸上
  // （一张卡的影子扫过另一张卡，那张卡上的字也该跟着暗）。底层在纸底下，画了看不见。
  //
  // selfH = 这一点自己有多高。桌面是 0，纸是它自己的高度 —— 于是纸不会被自己
  // 的影子盖住，但会被更高的东西（那一叠输入纸）的影子盖住。
  float sh = 0.0;
  if (uOver > 0.5) {
    vec4 self = texture2D(uOccl, vUv);
    // ⚠️ 半透明的纸（松动的纸淡出到一半）不算"这儿有纸"：它底下的桌面照旧接影子，
    //   否则一张快看不见的纸底下会空出一块没有影子的干净矩形。
    sh = castShadow(vUv, ar, self.a > 0.5 ? self.r : 0.0);
  }
  // 影子的浓淡跟着光走：正午实、斜阳浅、夜里最深（屋里没有第二个光源去填亮它）
  // ⭐⭐⭐ 纸对纸的投影。**素色版里这是白天唯一看得见的光效**，也是整套机制里
  // 唯一非实时计算做不出来的东西（一张纸的影子扫过另一张纸，鼠标划过时卡片
  // 抬起来影子跟着变）。实测它从前只把卡片周围压暗 8 到 10 个灰阶，
  // 而纯装饰的叶影压在卡片正文上是 23 —— 最值钱的一层比最像贴图的一层还安静。
  float shA = mix(0.26, 0.34, uNight) * mix(0.72, 1.15, alt) * (uLeaves > 0.0 ? 1.0 : 2.30);
  acc = lay(acc, mix(uDusk, uNightC, uNight * 0.7), sh * shA);

  // 时段色偏（只在顶层，很淡，只是让"几点了"读得出来）
  acc = lay(acc, uTint, uTintA * uOver * day);

  // 夜：屋子暗下来，台灯下留一汪。
  //
  // ⭐⭐ **分两层压，而且底层压得狠得多。** 第一版整片暗只挂在顶层（它盖住所有
  // 东西），于是桌面和纸被同一个数压，纸上的字跟着一起沉：实测最暗那张卡的标题
  // 对比度从白天的 10.2:1 掉到 **2.1:1** —— 用户报的「暗处太暗影响可用性」就是它。
  //
  // 分层之后各归各位：
  //   底层（在纸**下面**）—— 桌面、板子该黑就黑，夜的气氛全在这儿
  //   顶层（在纸**上面**）—— 只压一薄层统一色调，它盖着你正在读的那张纸
  //
  // 这也正是台灯底下的真实样子：周围一片黑，手边那张纸是亮的。
  // ⚠️ 判据不是「看着够不够黑」，是 lens.mjs 的 contrast 模式跟白天并排比。
  //    （这行原来带反引号 —— 而这段 CSS/GLSL 住在 JS 模板字符串里，一个反引号
  //     就把整个文件炸了。同一个坑这个月第四次，写注释先看看有没有反引号。）
  // ⭐⭐ **夜里没有叶影。** 太阳下去了，屋里的光源就是桌上那盏灯，树冠根本不在
  // 光路上 —— 上面那两笔的 day 因子已经把影和光一起收干净了，这儿也不再画
  // 「从叶隙漏下来的月光」。留着它的话，天黑之后屋里还站着一棵树。
  //
  // ⭐ 台灯那一汪不是圆的：灯口斜着照下来，光在桌上铺成一个**顺着影子方向**拉长的
  // 椭圆，跟纸的影子朝同一边。所以「灯在那个角上」这件事不用画一盏灯也读得出来。
  // ⚠️ 底数从 1.1 提到 1.35 是**补面积**：沿着 c 那一头放宽了，垂直那一头就得收紧，
  //   不然整片桌面被照亮的面积变大，夜就变浅了（夜的深浅是量过的，见下面那张表）。
  vec2 lp = (vUv - uFrom) * vec2(ar, 1.0);
  vec2 lq = vec2(dot(lp, n), dot(lp, c));
  lq.y *= 0.74;
  // ⚠️ 1.35 → 2.05：站主说台灯「有点暗淡」。病不在亮度在**边**：衰减太缓，
  //    光池铺满整屏就读成一层暖色滤镜，读不成一盏灯。收紧之后边缘可辨。
  float pool = exp(-dot(lq, lq) * 2.05);
  // 灯正下方那一小块更亮 —— 一盏灯该有个亮心，不然它只是一片均匀的暖雾。
  // ⛔ 亮心几乎只画在**桌面**那层。任何一层均匀的光压在内容上都会把字和纸一起
  //   提亮，而**提亮和压暗一样会吃掉对比度**（两边同时加同一个数，比值就往 1 走）。
  //   实测把亮心也给顶层，卡片标题从 4.2-4.5 掉到 3.9-4.1；只给桌面就没有这笔账。
  // ⭐ 亮心也收紧并提亮：一盏灯该有个能指出来的中心。
  float core = exp(-dot(lq, lq) * 7.2);
  acc = lay(acc, uLampC, uNight * (pool * mix(0.22, 0.32, uOver)
                                   + core * mix(0.26, 0.02, uOver)));
  // ⭐⭐ 池**外的桌面**往冷里偏。认灯认的是色温差，不是亮度差。
  //   ⛔ 这一笔第一版加在纸上（uOver），夜里卡片标题当场从 3.66 掉到 2.48 ——
  //   而站主早就说过暗处太暗影响可用性。**沉浸和可读性在这儿是一根跷跷板**，
  //   而桌面这一侧是免费的：它在纸底下，压得再狠也不动一个字。
  acc = lay(acc, uNightC, uNight * (1.0 - pool) * (1.0 - uOver) * 0.30);
  //
  // ⭐⭐ 08-30 第二次分账：**顶层再让一点，底层补上**（0.30/0.72 → 0.17/0.82）。
  //
  // ⚠️ 第三次（同日，用户判词「项目卡片和输入框不用单独立出来一层，
  // 保持在暗色里增加沉浸感」）：顶层又加回到 0.46/0.20。0.17 那一档纸太亮了 ——
  // 卡片 67% 压在 6% 的台面上，读起来是"一层亮纸浮在暗桌上"，不是"屋里黑着"。
  // 三档实测并排（web/scripts/lens.mjs + 接触印相）：
  //
  //   顶层 0.17  卡 67% 输入框 72%  ｜ 账目 3.5-3.9  日期 5.4   ← 分层感最重
  //   顶层 0.34  卡 47% 输入框 56%  ｜ 账目 3.0-3.3  日期 4.5
  //   顶层 0.46  卡 34% 输入框 45%  ｜ 账目 2.6-2.9  日期 3.8   ← 采用
  //
  // ⭐ 代价是明码的：顶层压的是**所有**东西，纸暗一分，板上的粉笔就跟着暗一分，
  // 而台面已经黑到 5% 了、再黑不动 —— 所以沉浸和板上字的对比度在这儿是一根跷跷板，
  // 不是可以两头都要的东西。选 0.46 是用户拍的板：账目那几行 2.6-2.9（白天 3.1-3.6），
  // 比白天弱一点点，但屋里是真的暗下来了。要往回退就调这一个数。
  // 站点上有一整类字是直接写在台面上的（左栏那本账、"我的项目"、橱窗大标题）。
  // 夜里它们得翻成粉笔才看得见 —— 可粉笔也在顶层底下：实测**顶层把纯白砍到 60%**，
  // 于是不管粉笔调多白，对台面的对比度都封死在 3.2:1。
  //
  // 关键在于两层压的东西不一样：
  //   顶层压在**内容之上** → 连字一起压，它决定了"最亮能有多亮"这个天花板
  //   底层压在**内容之下** → 只压台面，字一点不受影响
  // 所以把暗往底层挪：天花板抬起来了，台面照样那么黑，夜一点没变浅。
  // （整页均值实测几乎不动，变的是台面和字之间拉开了多少。）
  //
  // ⛔ 同时**底层那一刀不再让台灯掏空**（0.10 → 0.58）。原来光晕中心的台面几乎不压暗，
  // 于是夜里台面右半边是亮的、左半边是黑的 —— 一支粉笔伺候不了两种底：
  // 右边那句旁注量出来 1.08:1（粉笔写在亮处）。底层压的是**台面**，纸是不透明的
  // 盖在它上面，所以底层压得再匀也不会让台灯底下那张纸变暗 ——
  // **台灯照亮的是纸，不是桌子**。桌上还留一点光晕（0.84→0.58 的渐变），但不再掏空。
  acc = lay(acc, uNightC, uNight * (uOver > 0.5
    ? mix(0.46, 0.20, pool)      // 压在纸上
    : mix(0.84, 0.58, pool)));   // 压在桌面上：狠，而且**整片都狠**（见下）

  // ⚠️ 预乘输出。合成器那条路只有预乘是各家都靠谱的：非预乘（premultipliedAlpha:
  // false）在实测里画得出正确的缓冲区（readPixels 值全对），合成到页面上却几乎看不见。
  // 里头按直通 alpha 叠完（lay()），最后一步乘回去。
  gl_FragColor = vec4(acc.rgb * acc.a, acc.a);
}`;
