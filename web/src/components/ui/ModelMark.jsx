/** 这枚标的品牌色（按钮实心态要拿它当底色之类的场合） */
export function brandColor(brand) {
  return MARKS[brand]?.color || null;
}

/**
 * 铅笔线宽：≥40px 走视图单位常数，小图标走设备像素恒定。
 * @param {number} size 渲染高度（px）
 * @param {number} vbH  这枚标的 viewBox 高度（视图单位）
 */
function pencilWidth(size, vbH) {
  return size >= 40 ? 0.55 : Math.min(1.7, (0.95 * vbH) / size);
}

/**
 * @param {object} props
 * @param {string} props.brand   BRANDS 之一。不认识 → 什么都不画（服务端有断言兜着，
 *                               这里只可能是前端比服务端旧；宁可空着也不画错一家的标）
 * @param {number} [props.size]  渲染**高度**（px）；宽度按这枚标的外框比例放开
 * @param {string} [props.color] 覆盖品牌色（深色实心按钮上要换成纸色）
 * @param {boolean} [props.pencil] 要不要那道铅笔稿（默认要）
 * @param {boolean} [props.dark]   底是深色的（舞台卡的终端面）—— 有 onDark 的标改用那一档，
 *                                 并且**单色画**：两色关系是给纸面设计的，深底上分不出来
 */
export default function ModelMark({ brand, size = 16, color, pencil = true, dark = false, style }) {
  const mark = MARKS[brand];
  if (!mark) return null;
  const [x, y, w, h] = mark.vb;
  const onDark = dark && mark.onDark ? mark.onDark : null;
  const ink = color || onDark || mark.color;
  const sw = pencilWidth(size, h);
  const fillRule = mark.evenodd ? 'evenodd' : undefined;
  return (
    <svg
      width={Math.round((size * w) / h * 10) / 10} height={size}
      viewBox={`${x} ${y} ${w} ${h}`}
      aria-hidden="true" focusable="false"
      style={{ display: 'block', flexShrink: 0, overflow: 'visible', ...style }}
    >
      {pencil && mark.paths.map((p, i) => (
        <path
          key={`pen${i}`} d={p.d} fillRule={fillRule} fill="none"
          stroke={PAPER.ink2} strokeWidth={sw} strokeLinejoin="round" strokeLinecap="round"
        />
      ))}
      {mark.paths.map((p, i) => (
        <path key={i} d={p.d} fillRule={fillRule} fill={color || onDark || p.tint || ink} />
      ))}
    </svg>
  );
}
