/**
 * 分级渲染：镜头拉远到读不了的时候，卡片画名字而不画内容（2026-08-31）
 *
 * ## 它解决的是什么
 *
 * 站主的原话是「手机天生不适合无限画布」。但把 08-28 量到的那三个数摆在一起看，
 * 塌掉的其实不是画布：
 *
 *     17 件内容，视野里只有 3 件
 *     全内容入镜 = 0.19 倍
 *     一件能读的最小缩放 ≈ 0.8 倍
 *
 * 0.19 倍读不了的**不是画布，是卡片里的内容**。而在 0.19 倍上人也根本不需要读内容，
 * 他需要的是「板上有些什么、各自在哪、我在哪」—— 那点信息量一个名字就装得下。
 * 所以这里不做第二个画布，只是让同一块画布在拉远时**换一种画法**。
 *
 * 收益不止手机：桌面上拉远看全局时，几十张卡的活预览（iframe / 图 / markdown）
 * 全在渲染，这是「板一多就卡」的一个来源。远处不画内容，那份开销直接没了。
 *
 * ## ⭐ 判据是「卡片在屏幕上有多宽」，不是缩放百分比
 *
 * 站主定的：小于 120 物理像素就换标签。用渲染宽度而不是 scale，是因为板上卡片
 * 尺寸差得很远（一张便签 200 宽、一张站点卡 640 宽），同一个缩放下它们该不该
 * 画内容根本不是同一个答案。大卡在 0.3 倍上还读得动，小卡在 0.5 倍上就已经糊了。
 *
 * 120 这个数的来路：真正适合阅读的缩放区间是 70%~130%，而正文字号 12~16px，
 * 低于 120 物理像素的卡片一行放不下十个字，那时候画内容等于画噪点。
 *
 * ⚠️ 这跟 ArtifactCard 的 PREVIEW_MIN_SCALE(0.35) 不是一回事，别合并：
 * 那条管的是**开销**（活 iframe 挂不挂），这条管的是**能不能读**。两条都成立时
 * 这条先生效，但它们的理由不同，将来也会各自变。
 */

/** 卡片渲染宽度低于它就只画名字。改这个数之前先读上面那段「判据」。 */
export const LABEL_ONLY_W = 120;

/**
 * 名字也塞不下的时候（比这还窄）连字都不画，只留一个色块。
 * 12px 的字至少要这么宽才认得出是个词而不是一撇一捺。
 */
export const BLANK_W = 34;

/** 卡片此刻在屏幕上有多宽（物理像素） */
export function renderedW(worldW, scale) {
  const w = Number(worldW);
  const s = Number(scale);
  if (!Number.isFinite(w) || !Number.isFinite(s)) return 0;
  return w * s;
}

/**
 * 这张卡此刻该画到哪一档。
 * @returns {'full'|'label'|'blank'}
 */
export function lodOf(worldW, scale) {
  const px = renderedW(worldW, scale);
  if (px < BLANK_W) return 'blank';
  if (px < LABEL_ONLY_W) return 'label';
  return 'full';
}
