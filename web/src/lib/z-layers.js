/**
 * z-layers.js —— 全站层级档位表（2026-09-08）。
 *
 * ## 为什么不是一张平表
 *
 * z-index 只在**同一个层叠上下文**里比大小。这个仓库有一道承重的上下文边界：
 * `routes/ProjectWorkspace.jsx:2085` 的画布 section 上钉着 `isolation: 'isolate'`。
 *
 * 所以「画布里的产物窗 500」和「聊天栏 120」**不是 500 > 120 的关系** ——
 * 窗被关在画布那一格里，聊天栏在外面，聊天栏永远赢。那行 isolate 就是为了这个
 * 才加的（不隔离的话产物窗会把聊天栏盖死）。
 *
 * 拉平成一张表会把这件事说反，所以按上下文分三组，**只有同组内部可比**：
 *
 *   `BOARD_Z`   画布这一格里边（关在 isolate 里，数字再大也出不去）
 *   `SHELL_Z`   画布外边的工作区外壳
 *   `PORTAL_Z`  portal 到 body 的（脱离所有上下文，跟 SHELL_Z 在同一个平面上比）
 *
 * ⚠️ **跨组比数字没有意义。** 要压过聊天栏，只能 portal 出去，不能把数字调大 ——
 * 2026-08-13 右键菜单就栽在这儿：标着 9000 但关在画布里，右半截压在聊天栏底下
 * 点了没反应，菜单还开着，看起来像「这一项坏了」（全案见 `ContextMenu.jsx` 头注）。
 *
 * ## 什么该进这张表
 *
 * **跨文件比大小的**才进。一个组件内部自己那几层（`DragOverlay` 的 18~37、
 * `CommentMarkers` 的 9/11）是局部顺序，留在本地是对的 —— 搬进来只会让这张表
 * 变成一本没人看的流水账，反而没人再信它。
 *
 * 判据一句话：**这个数会不会跟另一个文件里的数比大小？** 会 → 进表。
 *
 * ## 档位之间留空
 *
 * 每档之间留出空当，插一层不用推倒重排。
 *
 * ⛔ **不许写 `某档 + 1`。** `CanvasFrame` 当年就是不 import 现成的
 * `ARTIFACT_WINDOW_Z`、手写了个 510（比产物窗大 1），于是那两层永远焊死、
 * 中间再也插不进东西。要插就在这张表里加一档，别在调用点做算术。
 *
 * ⛔ **别拿裸数字当层级。** 2026-08-24 之前 `BoardOverlays` 的阅读器写死 110，
 * 那是「压在 DeckWindow(120) 之下」的老账；08-07 窗层抬到 500 之后没人 rebase，
 * 于是文件夹窗里双击 .md，阅读器整个躲在窗后面，又是一次「双击没反应」。
 * 裸数字的问题不是不好看，是**它不会跟着别人一起改**。
 */

