/**
 * server/lib/screen.js —— 「一屏」的唯一基准（2026-08-29 纸范式刀 0）
 *
 * 纸范式拍板：一张纸 = **0.75 倍缩放下等于用户一屏**的矩形工作区。
 * 在这之前「一屏」有三个同源近邻值各自散落（fitFor 的 /0.8、board-place 的
 * ONE_SCREEN 1750×1125、sketch-layout 的 SKETCH_FIT 1700×1100），注释里互相
 * 提醒「改缩放基准要几处一起看」—— 现在基准只有这一份，改这里就是改全部。
 *
 * DEFAULT_SCREEN 是没有视点上报时的兜底屏（普通笔记本 1400×900）；真实纸尺寸
 * 永远优先按上报的 device 屏幕算（见 sketch-layout.js fitFor）。
 */

export const ZOOM_BASIS = 0.75;

/**
 * 手机的缩放基准（2026-09-01，站主拍板「手机端的默认缩放可以设置为 50%」）。
 *
 * 在这之前手机没有基准这一说：`fitFor` 给的是「一件 = 一屏」（宽 = 屏宽 − 48），
 * 也就是隐含 100%。那一档是 08-28 定的，前提是**手机上唯一可用的姿势是一件占满
 * 一屏、竖着翻** —— 而叠纸把那个前提换掉了：一摞纸原地翻页，屏幕不用再当纸筒使。
 *
 * 0.5 的意思是**纸 = 两个屏幕宽、两个屏幕高**，正好在 50% 下整页入镜。
 * ⚠️ 只有纸变大，别的一概不变（站主原话「其他显示比如字体大小不变」）——
 * 正文栏宽仍锁死一屏（见 fitFor 的 colW），所以放大到 100% 读一栏时一行正好一屏，
 * 零横向滑动。纸宽跟着放开的话 agent 会写出 780 宽的板书，那就必须横滑才读得完。
 */
export const PHONE_ZOOM_BASIS = 0.5;

export const DEFAULT_SCREEN = { w: 1400, h: 900 };

/** 兜底「一屏」世界像素（1400×900 ÷ 0.75 = 1867×1200） */
export const ONE_SCREEN = {
  w: Math.round(DEFAULT_SCREEN.w / ZOOM_BASIS),
  h: Math.round(DEFAULT_SCREEN.h / ZOOM_BASIS),
};

/**
 * 一张卡的高度天花板（2026-08-29 占位契约刀 B，站主定「一张纸的 40%」）。
 *
 * 生产真板上最高一条板书 **2471px** —— 312 宽、2471 高，一整章小说写成一根柱子。
 * 卡的高度原来完全由内容决定、没有上限，于是两件坏事同时发生：版面被柱子劈开，
 * 而落位系统按估算高度排好队之后，渲染回写又把卡撑大去压邻居。
 *
 * 定成固定值而不是「按当前纸算」，是因为卡的高度不该随看它的设备变 —— 同一块板
 * 在手机和大屏上看，卡的版面必须是同一个。384 = 16 格，也接近 973 高的纸的 40%。
 *
 * 超出的部分不是丢掉：卡上折叠（可展开，展开是临时的、不改占位），工具如实告诉
 * agent「你这条被折叠了，实际 N px」——「越界钳住但要说」。
 */
export const CARD_MAX_H = 384;
