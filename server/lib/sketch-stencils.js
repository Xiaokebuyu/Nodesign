export const STENCIL_NAMES = Object.keys(STENCILS);

/**
 * 展开一个词：缩放到 w×h（像素），返回未抖动的笔画（抖动由调用方按 seed 加 ——
 * 阵列的每份要各自的抖）。
 * @returns {{ strokes: string[], w:number, h:number }}
 */
export function stencilStrokes(name, wPx, hPx = null) {
  const st = STENCILS[name];
  if (!st) return null;
  const w = Math.max(8, wPx);
  const h = Math.max(8, hPx || w * st.aspect);
  // ⚠️ 奇偶计数器**每条笔画各自数**：跨笔画累计的话，一条 d 的数字个数为奇数
  // 就把后面所有笔画的 x/y 错位成 y/x
  return { strokes: st.strokes.map((d) => scaleD(d, w / 100, h / 100)), w, h };
}

function scaleD(d, sx, sy) {
  let k = 0;
  return d.replace(/-?\d*\.?\d+/g, (n) => {
    const v = Number(n) * ((k++ % 2 === 0) ? sx : sy);
    return String(Math.round(v * 10) / 10);
  }).replace(/,/g, ' ');
}
