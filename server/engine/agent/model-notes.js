/**
 * engine/agent/model-notes.js —— 站主对每条模型行的**印象短语**（2026-09-08）。
 *
 * 输入框上方那排贴纸，每张 = 一个模型名 + 一个状态色点 + 这里的一句短语。
 * 色点是机器算的（`lib/ingress/upstream-health.js` 的环形账），短语是**人写的**。
 *
 * ## 为什么单独一个文件，不写进 model-table 的行里
 *
 * 两个原因：
 *
 * 1. `model-table.js` 卡在行数棘轮的 600 行上限（09-08 时 598 行，只剩 2 行余量）。
 *    给十来行各加一个字段当场超标，而为了加一句文案去拆那张表是本末倒置。
 * 2. 更要紧的：**这两种东西的变更节奏完全不同**。路由表改一次要连着改闸、改测试、
 *    对账上游；印象短语是站主随手改的一句话，今天觉得"容量不足"明天觉得"最近还行"。
 *    混在一个文件里，改一句文案要动那张最敏感的表，谁都不敢改。
 *
 * ## 写什么
 *
 * ⛔ **这些话必须是站主自己说的**，不是从日志里推出来的、更不是我替他编的。
 * 它出现在用户眼前，署的是这个站的口吻。机器有话要说的话，说的是色点那一路
 * （"最近 12 发挂了 5 发"这种），不是这一路。
 *
 * 没写的行就没有短语，贴纸上只显示名字和色点 —— **留白是对的**，
 * 硬凑一句"性能均衡"之类的空话比没有更糟。
 *
 * ## 怎么加
 *
 * 键是 model-table 里的行 id（拼错不会报错，只是那行没短语；`model-notes.test.js`
 * 会对账，写了一个不存在的 id 当场红）。
 */

/** @type {Readonly<Record<string, string>>} 模型行 id → 站主的印象短语 */
export const MODEL_NOTES = Object.freeze({
  'kimi-k3': '容量不足',
});

/** @param {string} modelId @returns {string} 没写就是空串 */
export function noteOf(modelId) {
  return MODEL_NOTES[modelId] || '';
}
